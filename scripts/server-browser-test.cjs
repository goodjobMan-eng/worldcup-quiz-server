const { chromium } = require('playwright');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({executablePath:'/usr/bin/chromium',headless:true,args:['--no-sandbox','--enable-unsafe-swiftshader']});
  const page = await browser.newPage({viewport:{width:1280,height:900}});
  const errors=[]; page.on('pageerror',e=>errors.push(e.message));
  const session=()=>page.evaluate(()=>JSON.parse(localStorage.getItem('nationlab-session')));
  const state=()=>page.evaluate(()=>{const s=JSON.parse(localStorage.getItem('nationlab-session'));return JSON.parse(localStorage.getItem('nationlab-room-'+s.serverId+'--'+s.code)).state;});
  const enter=async(school,cl)=>{await page.getByLabel('학교 이름',{exact:true}).fill(school);await page.getByLabel('학급',{exact:true}).fill(cl);await page.getByRole('button',{name:'우리 교실 방 만들기',exact:true}).click();await page.getByRole('button',{name:'서버 바꾸기',exact:true}).waitFor();};
  try {
    await page.goto(process.env.NATIONLAB_URL || 'http://127.0.0.1:3000');
    assert.equal(await page.getByLabel('시·도교육청',{exact:true}).locator('option').count(),17);
    await page.getByLabel('시·도교육청',{exact:true}).selectOption('sejong');
    assert.equal(await page.getByLabel('교육지원청 서버',{exact:true}).inputValue(),'본청 직영');
    await page.getByLabel('시·도교육청',{exact:true}).selectOption('gyeonggi');
    await page.getByLabel('교육지원청 서버',{exact:true}).selectOption('수원');
    await page.getByLabel('접속 방식',{exact:true}).selectOption('local');
    await page.screenshot({path:'/workspace/onboarding/nationlab-server-selection.png',fullPage:true});
    await enter('한빛초등학교','6학년 1반');
    const first=await session(); assert.ok(first.serverId.startsWith('gyeonggi-'));
    assert.equal((await state()).classroom.school,'한빛초등학교');
    await page.getByRole('button',{name:'서버 바꾸기',exact:true}).click();
    await page.getByLabel('시·도교육청',{exact:true}).selectOption('seoul');
    await page.getByRole('button',{name:'학생',exact:true}).click();
    await page.getByLabel('방 코드',{exact:true}).fill(first.code);
    await page.getByLabel('나의 별명',{exact:true}).fill('다른서버');
    await page.getByRole('button',{name:'함께 시작하기',exact:true}).click();
    await page.getByRole('alert').filter({hasText:'방이 없어요'}).waitFor();
    assert.equal(await session(),null);
    await page.getByRole('button',{name:'선생님',exact:true}).click();
    await enter('새봄초등학교','6학년 2반');
    const second=await session();assert.notEqual(first.serverId,second.serverId);
    await page.getByRole('button',{name:'대한민국 월드',exact:true}).first().click();
    await page.waitForFunction(()=>document.querySelector('canvas[aria-label^="대한민국 입체 지도"]')?.dataset.renderer==='webgl');
    await page.getByRole('button',{name:/새봄초등학교 · 6학년 2반/}).click();
    await page.getByRole('button',{name:'지도 확대',exact:true}).click();
    await page.getByRole('button',{name:'전체 보기',exact:true}).click();
    await page.getByLabel('시·도교육청',{exact:true}).selectOption('gyeonggi');
    await page.getByRole('button',{name:/한빛초등학교 · 6학년 1반/}).waitFor();
    await page.getByRole('button',{name:/한빛초등학교 · 6학년 1반/}).click();
    assert.equal(await page.getByText('학교·학급이 공개한 건축물 2개 · 교육청을 선택해 둘러보세요.',{exact:true}).count(),1);
    await page.screenshot({path:'/workspace/onboarding/nationlab-korea-world.png',fullPage:true});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
    await page.reload();await page.getByRole('button',{name:'서버 바꾸기',exact:true}).waitFor();
    assert.equal((await session()).serverId,second.serverId);
    assert.equal((await state()).classroom.school,'새봄초등학교');
    assert.deepEqual(errors,[]);
    console.log('PASS: 17 education offices, district selection, class registration, cross-server room rejection, two schools visible in Korea world, camera controls, refresh persistence, tablet layout.');
  }catch(e){await page.screenshot({path:'/workspace/onboarding/nationlab-server-failure.png',fullPage:true});console.error((await page.locator('body').innerText()).slice(-3000));throw e;}finally{await browser.close();}
})().catch(e=>{console.error(e);process.exit(1)});
